"""Read boundary for the working board, independent of archive snapshots."""
from typing import Protocol
from uuid import UUID


class BoardRepository(Protocol):
    def list_boards(self) -> list[dict]: ...
    def structure(self, board_id: UUID) -> dict: ...
    def cards(self, board_id: UUID, column_id: UUID, lane_id: UUID | None, limit: int, cursor: str | None) -> dict: ...
    def image(self, attachment_id: UUID) -> dict: ...
    def file(self, attachment_id: UUID) -> dict: ...
    def detail(self, card_id: UUID) -> dict: ...
