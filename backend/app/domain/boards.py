"""Read boundary for the working board, independent of archive snapshots."""
from datetime import date
from typing import Protocol
from uuid import UUID


class BoardRepository(Protocol):
    def list_boards(self) -> list[dict]: ...
    def structure(self, board_id: UUID) -> dict: ...
    def filter_options(self, board_id: UUID) -> dict: ...
    def cards(self, board_id: UUID, column_id: UUID, lane_id: UUID | None, limit: int, cursor: str | None, archived: bool = False, query: str = '', tag_id: list[UUID] | None = None, user_id: list[UUID] | None = None, date_field: str = 'created', date_from: date | None = None, date_to: date | None = None, timezone_offset: int = 0) -> dict: ...
    def create_card(self, board_id: UUID, title: str, column_id: UUID, lane_id: UUID | None, request_id: UUID) -> dict: ...
    def image(self, attachment_id: UUID) -> dict: ...
    def file(self, attachment_id: UUID) -> dict: ...
    def detail(self, card_id: UUID) -> dict: ...
    def move_next(self, card_id: UUID, version: int) -> dict: ...
    def add_comment(self, card_id, request_id, text, files, upload_root) -> dict: ...
