"""Framework-independent boundaries implemented by archive and SQL adapters."""
from pathlib import Path
from typing import Protocol


class CardRepository(Protocol):
    def snapshots(self) -> list[dict]: ...
    def load_card(self, snapshot: str, card_id: int) -> dict: ...
    def dictionaries(self, snapshot: str) -> dict: ...
    def search(self, snapshot: str, query: str, offset: int, limit: int) -> dict: ...


class AttachmentStorage(Protocol):
    def asset_path(self, snapshot: str, card_id: int, index: int) -> tuple[Path, str]: ...
